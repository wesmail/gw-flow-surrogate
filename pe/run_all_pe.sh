#!/usr/bin/env bash
# All 8 PE runs on ONE machine: SNR 15, 30, 60, 120 x {NRHybSur3dq8 reference, our model}.
# (On a cluster use pe/pe_run.sbatch instead: all 8 at the same time.)
#
#   bash pe/run_all_pe.sh                        # reference runs in parallel (CPU), ours on the GPU
#   ONLY=fm bash pe/run_all_pe.sh                # only our model       (ONLY=nr: only the reference)
#   NR_PARALLEL=0 bash pe/run_all_pe.sh          # reference runs one at a time (cooler laptop)
#   SNRS="30" bash pe/run_all_pe.sh              # a subset
#   EXTRA="--nlive 500" bash pe/run_all_pe.sh    # extra run_pe.py options (same for ALL runs!)
#   THREADS=4                                    # numpy/BLAS threads per process (default 4)
#
# Runs resume from their checkpoint if interrupted. Start tokens run serially in each process
# (a worker pool was measured to be slower). Do not edit this file while it is running.
set -euo pipefail
: "${FT:?set FT to the flagship checkpoint (global_step 320333)}"
export LAL_DATA_PATH="${LAL_DATA_PATH:-$HOME/lal_data}"
THREADS="${THREADS:-4}"
export OMP_NUM_THREADS=$THREADS MKL_NUM_THREADS=$THREADS OPENBLAS_NUM_THREADS=$THREADS
SNRS="${SNRS:-15 30 60 120}"
ONLY="${ONLY:-all}"
NR_PARALLEL="${NR_PARALLEL:-1}"
OUT="${OUT:-results/pe}"
read -r -a EXTRA_ARGS <<< "${EXTRA:-}"
COMMON=(--checkpoint "$FT" --manifest data/n1000k/manifest.parquet
        --norm-stats data/n1000k/norm_stats.npz --asd asd/ET_HFLF_cryo_15km.txt --outdir "$OUT"
        "${EXTRA_ARGS[@]}")
mkdir -p "$OUT/logs"

pids=()
if [[ "$ONLY" != fm ]]; then
  for s in $SNRS; do
    echo "start: reference, SNR $s  (log: $OUT/logs/nr_snr$s.log)"
    if [[ "$NR_PARALLEL" == 1 ]]; then
      python pe/run_pe.py --model nr --snr "$s" "${COMMON[@]}" > "$OUT/logs/nr_snr$s.log" 2>&1 &
      pids+=($!)
    else
      python pe/run_pe.py --model nr --snr "$s" "${COMMON[@]}" > "$OUT/logs/nr_snr$s.log" 2>&1
    fi
  done
fi
if [[ "$ONLY" != nr ]]; then
  for s in $SNRS; do
    echo "start: our model, SNR $s  (log: $OUT/logs/fm_snr$s.log)"
    python pe/run_pe.py --model fm --snr "$s" "${COMMON[@]}" > "$OUT/logs/fm_snr$s.log" 2>&1
  done
fi
for p in "${pids[@]}"; do wait "$p"; done
echo "all done:"; ls "$OUT"/*/summary.json